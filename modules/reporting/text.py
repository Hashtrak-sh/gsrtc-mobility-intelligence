"""Static report wording: methodology, limitations and scale-up needs (shared by the PDF and the downloadable note).

Numbers that come from configuration are formatted from ``config`` so the text cannot drift from the code.
"""
from __future__ import annotations

import config
from modules.reporting.exports import LIMITATIONS
from modules.ui import fmt

SIM_STATEMENT = (f"{config.SIMULATION_BADGE_TEXT}. Passenger, ticket, fare, survey, competitor, infrastructure and CCTV-stream values in this "
                 "report are simulated. They are not real GSRTC measurements, schedules or competitor data.")

FOOTER = f"{config.SIMULATION_BADGE_TEXT} \u2014 not GSRTC data"


def methodology() -> list[tuple[str, str]]:
    """(heading, text) pairs: how every number in the report is produced."""
    return [
        ("Data", f"All mobility data are generated by a deterministic simulator (seed {config.SEED}) over 42 days. Real geography is limited to "
                 "OpenStreetMap place coordinates and road geometry; stops placed near a real place are marked as such. Routes, timetables, "
                 "tickets, fares, surveys, competitors and assessments are synthetic."),
        ("Route KPIs", "Load factor = passenger-km / seat-km. EPKM = ticket revenue / vehicle-km. Contribution = ticket revenue - operating cost "
                       "(it is not profit; overheads, staff, depreciation and subsidy are not modelled). On-time = departure between 1 minute early "
                       "and 5 minutes late. Route KPIs always cover all 42 days; they do not change with the day-type filter."),
        ("Demand and gaps", f"Ticketed demand is censored at bus capacity, so crowding gaps are lower bounds. A route-hour is crowded when estimated demand "
                            f"exceeds {fmt.times(config.CROWDING_GAP_INDEX_THRESHOLD, 1)} its seats. Where the state timetable has no seats but private "
                            f"operators run, demand is a proxy that assumes {fmt.ratio_pct(config.PRIVATE_MARKET_OCCUPANCY_ASSUMPTION)} occupancy of "
                            "private seats (an assumption, not an observation)."),
        ("Recommendations", "Recommendations are produced by transparent rules from the gap, route-summary and score tables. Each states its evidence, "
                            f"assumptions, expected impact and constraints. Service scenarios target a {fmt.ratio_pct(config.SERVICE_TARGET_LOAD_FACTOR)} load "
                            f"factor; the state is assumed to capture {fmt.ratio_pct(config.STATE_CAPTURE_SHARE)} of the private-market proxy demand in an "
                            "uncovered window, with a sensitivity range shown. Fleet, crew and depot limits are not modelled."),
        ("Route scores", "Route potential scores are a rule-based weighted index (weights version demo-v1), not an AI prediction. Minimum-service and "
                         "social-importance constraints protect essential services: a low commercial score never alone recommends removal."),
        ("Competition and pricing", "The competitive gap score combines departure-slot, seat-share, premium-bus, fare and review-theme components with "
                                    "stated weights. The pricing scenario is demand_new = demand x (new fare / old fare) ^ elasticity, capped at seats. "
                                    f"Elasticity is an assumption (default {config.PRICING_ELASTICITY_DEFAULT}); a sensitivity table is shown."),
        ("Survey", "Descriptive survey shares describe the synthetic sample only and are unweighted. The switch-intent model is illustrative: it is fitted "
                   "to a synthetic survey generated by a known formula, so it can only recover that formula."),
        ("Ridership model", "A gradient-boosting model and a ridge model are compared with two simple baselines on a time-based train/test split of "
                            "synthetic history. Metrics are synthetic demonstration metrics and say nothing about real forecasting skill."),
        ("CCTV", "CCTV analysis counts aggregate movements only; there is no face or identity recognition and no person-level identifier is kept. "
                 "Counts from a detector run are never merged with the synthetic CCTV stream. A detector count is not claimed accurate without a "
                 "manual spot-check against the clip."),
    ]


def limitations() -> list[str]:
    return list(LIMITATIONS) + [
        "Real geography and synthetic mobility data are different things: OpenStreetMap supplies places and roads only.",
        "Demand outside ticketed boardings (people who could not board, private-vehicle trips) is assumed, not measured.",
        "Recommendations are indicative; feasibility (fleet, crew, depots, regulation) is not assessed.",
        "Model and survey results are illustrative and conditional on the synthetic setup.",
    ]


SCALE_UP: list[tuple[str, str]] = [
    ("ETM / ticketing data", "Real electronic-ticketing-machine transactions (boarding and alighting stops, fares, time) to replace simulated tickets "
                             "and remove the capacity-censoring blind spot."),
    ("GPS / AVL feeds", "Vehicle location histories to measure actual departure times, running times and reliability instead of simulated delays."),
    ("Schedules and fleet data", "Official timetables, trip patterns, fleet, crew and depot constraints to make service recommendations feasible."),
    ("Surveys", "A designed on-board and household survey with a sampling plan and weights, replacing the synthetic survey and its illustrative model."),
    ("Competitor and fare observation", "Observed private-operator timetables, fares and occupancy to replace the assumed private-market demand proxy."),
    ("Permitted CCTV / sensor counts", "Aggregate counts from permitted cameras at stations and stops, validated by manual spot-checks, replacing the "
                                       "synthetic CCTV stream."),
    ("Asset audits", "Field audits of stations, depots and digital systems to replace the synthetic infrastructure and digital scores."),
]


def methodology_markdown(filters_text: str | None = None, generated: str | None = None) -> str:
    """The one-page methodology and limitations note as Markdown."""
    out = ["# GSRTC Mobility Intelligence: methodology and limitations", "", f"**{config.SIMULATION_BADGE_TEXT}.** {SIM_STATEMENT}", ""]
    if generated:
        out += [f"Generated: {generated}", ""]
    if filters_text:
        out += [f"Filters at generation: {filters_text}", ""]
    out += ["## Methodology", ""] + [f"- **{h}.** {t}" for h, t in methodology()]
    out += ["", "## Limitations", ""] + [f"- {x}" for x in limitations()]
    out += ["", "## What a scale-up needs", ""] + [f"- **{h}.** {t}" for h, t in SCALE_UP]
    return "\n".join(out) + "\n"
