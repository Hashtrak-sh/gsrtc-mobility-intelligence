"""Streamlit panels for the optional LLM features ("Ask the Data" and the machine-generated theme summary).

Kept out of the page scripts so the pages stay small. Nothing here is required for the app to work; without a configured key the
panels show a clear unavailable message, and "Ask the Data" offers clearly labelled rule-based lookups (never presented as an LLM).
"""
from __future__ import annotations

import pandas as pd
import streamlit as st

from modules.llm import client as C
from modules.llm import rules as R
from modules.llm import summary as S
from modules.reporting import sources


def _show_ask_result(res: C.AskResult) -> None:
    if res.status in ("unavailable", "refused", "truncated", "error"):
        (st.warning if res.status != "error" else st.error)(res.message or "The question could not be answered.")
        return
    if res.supported:
        st.markdown(res.answer)
    else:
        st.warning("The data summary does not support a verified answer to this question."
                   + (" " + res.message if res.message else ""))
        if res.answer:
            with st.expander("Model's unverified text (do not rely on it)"):
                st.markdown(res.answer)
    if res.cited_tables:
        st.markdown("**Cited tables:** " + ", ".join(f"`{t}`" for t in res.cited_tables))
    if res.figures_used:
        st.dataframe(pd.DataFrame(res.figures_used).rename(columns={"label": "Figure", "value": "Value", "table": "Table", "verified": "Found in summary"}),
                     hide_index=True, width="stretch")
    for w in res.warnings:
        st.warning(w)
    if res.caveats:
        st.caption("Caveats: " + res.caveats)
    st.caption(C.MACHINE_LABEL + (" (served from the local cache)" if res.cached else "") + f" Model: {res.model}. Synthetic demonstration data.")


def ask_the_data_panel(tables: dict[str, pd.DataFrame] | None = None) -> None:
    """The "Ask the Data (optional)" section."""
    tables = tables if tables is not None else sources.load_tables()
    st.subheader("Ask the Data (optional)")
    ok, reason = C.llm_status()
    if ok:
        st.caption("Answers come only from a compact summary of the processed tables (see the cited tables). " + C.MACHINE_LABEL)
        q = st.text_input("Your question", key="ask_q", max_chars=C.MAX_QUESTION_CHARS, placeholder="Which route has the highest load factor?")
        if st.button("Ask", key="ask_go", disabled=not q.strip()):
            with st.spinner("Asking the model about the data summary..."):
                st.session_state["ask_result"] = C.ask_the_data(q, S.build_summary(tables))
        res = st.session_state.get("ask_result")
        if res is not None:
            _show_ask_result(res)
        with st.expander("What the model is given"):
            st.code(S.summary_json(S.build_summary(tables))[:6000] + " ...", language="json")
        return
    st.info("LLM not configured: set ANTHROPIC_API_KEY (or ANTHROPIC_AUTH_TOKEN) in the environment or .streamlit/secrets.toml and "
            "`pip install anthropic` to ask free-form questions. The app works fully without it.")
    st.caption(f"Status: {reason}")
    st.markdown("**Example questions with rule-based lookups** (fixed lookups over the processed tables; these are not LLM answers)")
    choice = st.selectbox("Example question", list(R.EXAMPLES) + ["Something else (unsupported)"], key="ask_example")
    typed = st.text_input("Or type a question", key="ask_typed", max_chars=C.MAX_QUESTION_CHARS)
    question = typed.strip() or (choice if not choice.startswith("Something else") else "")
    if question:
        ans = R.answer(question, tables)
        with st.container(border=True):
            st.markdown(f"**{ans.label}**")
            (st.markdown if ans.supported else st.warning)(ans.answer)
            if ans.cited_tables:
                st.caption("Source table(s): " + ", ".join(ans.cited_tables) + ". Synthetic demonstration data.")


def theme_summary_panel(survey_texts: list[str]) -> None:
    """Small optional section for Demand & Surveys; runs only on a button click and only if an LLM is configured."""
    ok, reason = C.llm_status()
    if not ok:
        st.caption("Machine-generated theme summary of the open-text answers is optional and needs an Anthropic API key (not configured). "
                   "The keyword-based check above does not need one.")
        return
    with st.expander("Machine-generated theme summary (optional)"):
        st.caption("Generated by an LLM from a deterministic sample of up to 200 synthetic open-text answers. It can be wrong; "
                   "descriptive shares above are the reliable figures. Results are cached.")
        if st.button("Generate theme summary", key="theme_go"):
            with st.spinner("Summarising themes..."):
                st.session_state["theme_result"] = C.summarise_themes(survey_texts)
        res = st.session_state.get("theme_result")
        if res is None:
            return
        if res.status != "ok":
            st.warning(res.message or "The theme summary could not be produced.")
            return
        for th in res.themes:
            share = "" if th["approx_share_pct"] is None else f" (about {th['approx_share_pct']:.0f}% of the sample)"
            st.markdown(f"**{th['theme']}**{share}. {th['description']}")
            for qt in th["example_quotes"]:
                st.markdown(f"> {qt}")
        for w in res.warnings:
            st.caption(w)
        st.caption(f"Machine-generated from {res.n_texts_used} synthetic texts; model {res.model}" + (" (cached)" if res.cached else "") + ". Not a substitute for analysis.")
