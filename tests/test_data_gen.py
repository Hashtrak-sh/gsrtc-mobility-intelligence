def test_validate_catches_negative_occupancy(tables):
    bad = {k: v.copy() for k, v in tables.items()}
    tk = bad["tickets"]
    # swap origin and destination of a ticket -> alighting before boarding
    i = 0
    tk.loc[i, ["origin_stop_id", "dest_stop_id"]] = tk.loc[i, ["dest_stop_id", "origin_stop_id"]].to_numpy()
