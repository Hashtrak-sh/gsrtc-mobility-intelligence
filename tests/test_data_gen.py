def test_osm_cache_is_used_and_labelled(tables):
    cache = G.load_osm_cache()
    if cache is None:
        pytest.skip("OSM cache not present (run python -m modules.data_gen.fetch_osm)")
    z, s = tables["zones"], tables["stops"]
    assert (s["coord_source"] == "openstreetmap").any() and (z["coord_source"] == "openstreetmap").any()
    osm_coords = {(round(r.lat, 6), round(r.lon, 6)) for r in cache.itertuples()}
    for df in (z, s):
        exact = df[df["coord_source"] == "openstreetmap"]
        assert all((round(a, 6), round(b, 6)) in osm_coords for a, b in zip(exact["lat"], exact["lon"]))
    assert not ((s["coord_source"] == "openstreetmap_offset") & (s["source_type"] == "openstreetmap")).any()
    assert set(s.loc[s["source_type"] == "openstreetmap", "stop_type"]) <= {"bus_stand", "intercity_terminal"}


